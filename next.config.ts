import type { NextConfig } from "next";

// When this app is served through the platform's session-scoped proxy
// (e.g. /api/build/sessions/{session_id}/webapp), NEXT_PUBLIC_BASE_PATH is
// set by the sandbox process launcher so Next.js can natively prefix every
// asset path, route, and the paths embedded in inline scripts (including
// the RSC hydration payload and Turbopack's own chunk-loading runtime).
// Regex-rewriting the served HTML/JS after the fact cannot safely
// distinguish real asset-loading references from hydration-payload data
// inside inline <script> tags - both look like plain text - so this must
// be handled natively by Next.js itself via basePath/assetPrefix.
const basePath = process.env.NEXT_PUBLIC_BASE_PATH || "";

const nextConfig: NextConfig = {
  ...(basePath ? { basePath, assetPrefix: basePath } : {}),

  // Previews are built with `next build` rather than served by `next dev`,
  // because Turbopack's dev client will not bootstrap without a working HMR
  // WebSocket and the platform proxy speaks HTTP only.
  //
  // `next build` fails hard on any type or lint error, where `next dev` would
  // still render the page. This code is generated by an agent, so a stray type
  // error is routine — and a preview that refuses to render because of one is
  // far worse than a preview with an imperfect type. The agent still sees these
  // errors in nextjs.log and can fix them.
  // (Next 16 dropped the `eslint` config key; `next build` no longer lints.)
  typescript: { ignoreBuildErrors: true },
};

export default nextConfig;
